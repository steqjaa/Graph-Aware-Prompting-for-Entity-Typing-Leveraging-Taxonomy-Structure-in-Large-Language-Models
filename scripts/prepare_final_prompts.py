"""Reconstruct v6 from frozen v5 tasks and the recorded external demonstration.

This is a reconstructed migration, not a claim to recover the original unsaved
terminal code. Verification compares every generated byte with the used prompts.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def build(output, verify=True):
    if output.exists():
        raise ValueError('Choose a new output directory; frozen prompts are never overwritten')
    provenance = json.loads((ROOT / 'external_example/provenance.json').read_text())
    if provenance['entity_id'] != 'wd:Q18720219' or not provenance['outside_evaluation_cohort']:
        raise ValueError('Unexpected demonstration provenance')
    for part in ('all_1k', 'children_removed'):
        rows = list(csv.DictReader((ROOT / f'prompts_v5/{part}/manifest.csv').open()))
        outrows = []
        for row in rows:
            old_prompt = (ROOT / row['prompt_path']).read_text()
            template = (ROOT / f'prompts_v5/{part}/example_0002/{row["condition"]}_prompt.txt').read_text()
            head = template.split('Now classify:', 1)[0]
            head = head.replace('Katsuhiro Harada', provenance['entity_label']).replace('Japanese video game producer', provenance['description'])
            text = head + 'Now classify:' + old_prompt.split('Now classify:', 1)[1]
            rel = Path(row['prompt_path']).relative_to('prompts_v5')
            path = output / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            meta = json.loads((ROOT / row['metadata_path']).read_text())
            meta.update(prompt_version='v6-external-demo', demonstration_omitted=False,
                        demonstration_entity_id=provenance['entity_id'],
                        demonstration_entity_label=provenance['entity_label'],
                        demonstration_source='external_example/provenance.json')
            (output / Path(row['metadata_path']).relative_to('prompts_v5')).write_text(json.dumps(meta, indent=2, ensure_ascii=False))
            newrow = dict(row, prompt_path=row['prompt_path'].replace('prompts_v5/', 'prompts_v6/'),
                          metadata_path=row['metadata_path'].replace('prompts_v5/', 'prompts_v6/'))
            if part == 'children_removed':
                source = output / 'all_1k' / path.parent.name / (row['source_condition'] + '_prompt.txt')
                newrow['source_prompt_sha256'] = hashlib.sha256(source.read_bytes()).hexdigest()
            outrows.append(newrow)
        with (output / part / 'manifest.csv').open('w', newline='') as handle:
            writer = csv.DictWriter(handle, fieldnames=outrows[0]); writer.writeheader(); writer.writerows(outrows)
        design = dict(entities=1000 if part=='all_1k' else 451, prompts=len(outrows),
                      demonstration='Rod Fergusson, wd:Q18720219; external to evaluation cohort',
                      demonstration_omitted=0, source='external_example/provenance.json')
        (output / part / 'design.json').write_text(json.dumps(design, indent=2))
    if verify:
        differences = []
        for generated in output.rglob('*'):
            if generated.is_file():
                expected = ROOT / 'prompts_v6' / generated.relative_to(output)
                if generated.read_bytes() != expected.read_bytes():
                    differences.append(str(generated.relative_to(output)))
        if differences:
            raise ValueError(f'Frozen v6 reconstruction differs: {differences[:10]} ({len(differences)} files)')
        print('All 10,353 prompts, 1,451 metadata files and both manifests/design files match the frozen experiment.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--no-verify', action='store_true')
    args = parser.parse_args()
    build(args.output.resolve(), verify=not args.no_verify)
